import React from 'react';
import {readFileSync} from 'node:fs';
import {describe,it,expect,afterEach} from 'vitest';
import {render,screen,cleanup,fireEvent} from '@testing-library/react';
import {MemoryRouter} from 'react-router-dom';
import UnifiedFanworkCatalogue from '../src/UnifiedFanworkCatalogue.jsx';
import {MODERN_FANFICTION_LINKS} from '../src/palaceFanfictionDiscovery.js';

afterEach(cleanup);
const hosted=[
 {id:'reading-focus-1',work_type:'fanwork',slug:'reader-one',title:'Palace Story A',
  rating:'general',summary:'A published hosted fanfiction',profiles:{display_name:'A Writer'},
  work_tags:[{tags:{name:'Naruto',category:'fandom'}}]},
 {id:'reading-focus-2',work_type:'fanwork',slug:'reader-two',title:'Palace Story B',
  rating:'teen',summary:'Another published hosted fanfiction',profiles:{display_name:'B Writer'},
  work_tags:[{tags:{name:'Naruto',category:'fandom'}}]}
];
const source=MODERN_FANFICTION_LINKS.find(x=>x.id==='anime-animeisperfection-frozen-heart');
const show=()=>render(<MemoryRouter><UnifiedFanworkCatalogue publishedWorks={hosted} externalWorks={[source]}/></MemoryRouter>);

describe('Fanfiction reading-first experience',()=>{
 it('makes hosted editions visibly distinct from credited external links and reads here first',()=>{
  show();
  expect(screen.getByRole('heading',{name:'Read here on the Palace'})).toBeTruthy();
  expect(screen.getByRole('heading',{name:'Explore original author sites'})).toBeTruthy();
  expect(screen.getByRole('combobox',{name:/Order/i}).value).toBe('source');
  expect(screen.getAllByRole('link',{name:/Read on the Palace/})).toHaveLength(2);
  const external=screen.getByRole('link',{name:/Read at original source/});
  expect(external.getAttribute('target')).toBe('_blank');
  expect(external.getAttribute('rel')).toContain('noopener');
  const cards=document.querySelectorAll('.palace-unified-card');
  expect(cards).toHaveLength(3);
  expect(cards[0].classList.contains('source-hosted')).toBe(true);
  expect(cards[2].classList.contains('source-external')).toBe(true);
 });
 it('keeps the reading destination selector and advanced filters accessible',()=>{
  show();
  expect(screen.getByRole('combobox',{name:/Read from/}).value).toBe('all');
  fireEvent.change(screen.getByRole('combobox',{name:/Read from/}),{target:{value:'linked'}});
  expect(screen.queryByRole('link',{name:/Read on the Palace/})).toBeNull();
  expect(screen.getByRole('link',{name:/Read at original source/})).toBeTruthy();
  fireEvent.click(screen.getByText('More filters'));
  expect(screen.getByRole('combobox',{name:/Rating/})).toBeTruthy();
  fireEvent.click(screen.getByRole('button',{name:/Anime & manga/}));
  expect(screen.getByRole('button',{name:/Anime & manga/}).getAttribute('aria-pressed')).toBe('true');
  fireEvent.click(screen.getByRole('button',{name:/Clear filters/}));
  expect(screen.getByRole('combobox',{name:/Read from/}).value).toBe('all');
 });
 it('preserves an age-restricted, source-aware discovery policy',()=>{
  const jsx=readFileSync('src/UnifiedFanworkCatalogue.jsx','utf8');
  expect(jsx).toContain('filterUnifiedFanworks');
  expect(jsx).toContain('includeMature');
  expect(jsx).toContain('Author notes &amp; reuse terms');
  expect(jsx).toContain('underlying franchise rights');
  expect(jsx).not.toMatch(/created by chatgpt|generated by chatgpt/i);
 });
 it('places discovery before generic archive controls and excludes redundant fandom scaffolding',()=>{
  const live=readFileSync('src/liveRooms.jsx','utf8');
  const catalogue=live.indexOf("origin==='fandom'&&!advancedView&&<>");
  const scope=live.indexOf('reading-scope-selector reading-scope-calm');
  expect(catalogue).toBeGreaterThan(0);
  expect(catalogue).toBeLessThan(scope);
  expect(live).toContain("origin!=='fandom'&&<section className=\"reading-scope-selector");
  expect(live).toContain("session&&origin!=='fandom'&&<section className=\"reading-reader-lenses");
  expect(live).toContain('fanfictionActiveFilters.length>0');
  expect(live).toContain('fanfiction-focused');
  expect(live).not.toContain("scrollIntoView({block:'start'})");
 });
 it('loads mobile, Daylight and Nightfall focused styling after the prior theme fixes',()=>{
  const main=readFileSync('src/main.jsx','utf8');
  const css=readFileSync('src/fanfiction-reading-polish.css','utf8');
  expect(main.indexOf("import './fanfiction-reading-polish.css';")).toBeGreaterThan(main.indexOf("import './reading-theme-contrast-repair.css';"));
  expect(css).toContain('.daylight .chic-reading-page.fanfiction-focused');
  expect(css).toContain('--fan-text:#eff3ff');
  expect(css).toContain('--fan-text:#27344d');
  expect(css).toContain('padding-bottom:calc(152px + env(safe-area-inset-bottom,0px))');
  expect(css).toContain('@media(forced-colors:active)');
  expect(css).toContain('@media(prefers-reduced-motion:reduce)');
 });
});
